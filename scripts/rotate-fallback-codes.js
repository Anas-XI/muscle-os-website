/**
 * Rotate fallback codes — generates 5 fresh codes, hashes them,
 * and rewrites assets/data/access-codes.json in one command.
 *
 * Usage:
 *   node scripts/rotate-fallback-codes.js
 *
 * Output: prints the new codes and overwrites access-codes.json.
 *
 * Run this monthly (set a recurring reminder) so that even if a
 * static fallback code leaks, its useful lifetime is bounded.
 *
 * The codes are printed to console — save them somewhere safe
 * (password manager, or just the WhatsApp chat with yourself)
 * so you can share them with customers if needed during a Worker outage.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const CODES_PATH = path.join(__dirname, '..', 'assets', 'data', 'access-codes.json');

// Product definitions: [label, productIds, plan, durationDays]
const PRODUCTS = [
  ['Master (all products)', 'all', 'master', 30],
  ['Training Tool',         ['training_tool'], 'single_product', 30],
  ['TDEE Engine',           ['tdee_adaptive_engine'], 'single_product', 30],
  ['Training Book',         ['training_book'], 'book_purchase', 0],
  ['Nutrition Book',        ['nutrition_book'], 'book_purchase', 0],
];

const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
function randomCode(prefix) {
  let result = prefix + '-';
  for (let i = 0; i < 10; i++) {
    result += chars[Math.floor(Math.random() * chars.length)];
  }
  return result;
}

var hashes = {};
var plaintexts = [];

PRODUCTS.forEach(function(p, i) {
  var prefix = ['MASTER', 'TOOL', 'TDEE', 'BOOK-T', 'BOOK-N'][i];
  var code = randomCode(prefix);
  var hash = crypto.createHash('sha256').update(code).digest('hex');
  var entry = { plan: p[2] };
  entry.productId = p[1];
  entry.durationDays = p[3];
  // For books (durationDays 0), omit the field since it means lifetime
  if (entry.durationDays === 0) delete entry.durationDays;
  hashes[hash] = entry;
  plaintexts.push({ label: p[0], code: code, hash: hash });
});

var output = {
  version: 2,
  note: 'Hashed access codes — never store plaintext codes here. Generated by scripts/rotate-fallback-codes.js. Run monthly.',
  hashes: hashes
};

fs.writeFileSync(CODES_PATH, JSON.stringify(output, null, 2) + '\n');

console.log('\n=== NEW FALLBACK CODES GENERATED ===\n');
console.log('access-codes.json has been updated.\n');
console.log('Plaintext codes (SAVE THESE):\n');
plaintexts.forEach(function(p) {
  console.log('  ' + p.label + ': ' + p.code);
});
console.log('\nAdd these to your password manager or personal notes.');
console.log('Run this script again in ~30 days.\n');
